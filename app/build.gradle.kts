import java.util.Properties

val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun localProp(key: String, default: String = ""): String =
    (localProps.getProperty(key) ?: default).replace("\\", "\\\\").replace("\"", "\\\"")

// ---------------------------------------------------------------------------
// Signing secrets: local.properties first, then the process environment (CI
// injects these via `env:` on the build step). Nothing here is ever committed —
// only the *config* that reads it is.
// ---------------------------------------------------------------------------
fun secret(key: String, default: String = ""): String =
    localProps.getProperty(key) ?: System.getenv(key) ?: default

// ---------------------------------------------------------------------------
// Version — ONE derivation for local builds and CI.
//
//   versionName = the committed VERSION file (single source of truth)
//   versionCode = git commit count + VERSION_CODE_OFFSET
//
// There is deliberately no `github.run_number` input any more: run_number only
// exists in CI, so a local build used to fall back to 1 and every local install
// was a downgrade against a published CI APK.
//
// OFFSET is needed because the debug APKs published before this change used
// github.run_number as versionCode (latest = v0.1.13, i.e. run #13) and the git
// history already holds 67 commits. Starting the new scheme at 100 keeps every
// future build strictly greater than every previously published one, so
// "update" keeps installing over the old APK instead of failing as a downgrade.
//
// A *shallow* clone (actions/checkout default depth=1) has no history to count,
// so it is an error rather than a silent fallback to a lower number. Both
// workflows pass fetch-depth: 0.
// ---------------------------------------------------------------------------
val versionNameFile = rootProject.file("VERSION")
require(versionNameFile.exists()) { "VERSION file is missing at ${versionNameFile.path}" }
val orhanVersionName: String = versionNameFile.readText().trim()
require(Regex("""^\d+\.\d+\.\d+$""").matches(orhanVersionName)) {
    "VERSION must look like MAJOR.MINOR.PATCH, found '$orhanVersionName'"
}

val versionCodeOffset = (providers.gradleProperty("versionCodeOffset").orNull
    ?: System.getenv("VERSION_CODE_OFFSET")
    ?: "100").toInt()

val gitCommitCount: Int = try {
    val proc = providers.exec {
        commandLine("git", "rev-list", "--count", "HEAD")
        isIgnoreExitValue = true
    }
    val out = proc.standardOutput.asText.get().trim()
    out.toIntOrNull() ?: -1
} catch (e: Exception) {
    -1
}
require(gitCommitCount > 0) {
    """
    Could not read the git commit count (got '$gitCommitCount').

    versionCode is derived from `git rev-list --count HEAD`, so the build needs
    the full history. In CI check out with:

        - uses: actions/checkout@<sha>
          with:
            fetch-depth: 0

    Locally, a full clone works as-is; for a shallow one run
    `git fetch --unshallow` first.
    """.trimIndent()
}

val orhanVersionCode: Int = gitCommitCount + versionCodeOffset

