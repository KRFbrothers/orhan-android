// Fail a *signed* release build early when signing material is missing.
//
// `-PallowUnsignedRelease=true` is the explicit opt-out used by the PR checks
// workflow, which only needs `assembleRelease` to prove R8 runs on code nobody
// ships. Any release build that is meant to be installed fails here instead of
// quietly emitting an unsigned APK.
val allowUnsignedRelease = (providers.gradleProperty("allowUnsignedRelease").orNull
    ?: System.getenv("ALLOW_UNSIGNED_RELEASE") ?: "false").toBoolean()

gradle.taskGraph.whenReady {
    if (allowUnsignedRelease) return@whenReady
    val releaseRequested = allTasks.any {
        it.project == project && it.name.contains("Release") &&
            (it.name.startsWith("assemble") || it.name.startsWith("bundle") || it.name.startsWith("package"))
    }
    if (releaseRequested) {
        val cfg = android.signingConfigs.getByName("release")
        require(cfg.storeFile != null && cfg.storeFile!!.exists()) {
            "Release signing is not configured: set ORHAN_KEYSTORE_PATH (env or local.properties) to a keystore file, or pass -PallowUnsignedRelease=true for a compile-only check."
        }
        require(!cfg.storePassword.isNullOrBlank() && !cfg.keyAlias.isNullOrBlank()) {
            "Release signing is not configured: set ORHAN_KEYSTORE_PASSWORD and ORHAN_KEY_ALIAS (env or local.properties)."
        }
    }
}

// Single source of truth: THIRD-PARTY-NOTICES.md + licenses/*.txt at repo root are copied
// into generated assets at build time, so the in-app text can never drift from the repo.
val copyLicenseAssets by tasks.registering(Copy::class) {
    from(rootProject.file("THIRD-PARTY-NOTICES.md"))
    from(rootProject.file("licenses")) { into("licenses") }
    into(layout.buildDirectory.dir("generated/licenseAssets/oss"))
}
tasks.named("preBuild") { dependsOn(copyLicenseAssets) }
